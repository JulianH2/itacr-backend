-- =============================================================================
-- Object:      dbo.usp_Order_CreatePickup
-- Type:        stored procedure
-- Purpose:     Saves the pickup order of a customer without an account, in one transaction: it finds the customer by
--              phone (or creates it, and keeps the name just typed), checks the limit of active orders of that phone,
--              and saves the order, its items, and its first status history row. The range locks make two requests at
--              the same moment wait for each other, so a phone can never go over the limit and the same ClientOrderId
--              can never be saved twice. Nothing is saved unless the outcome is Created.
-- Parameters:  @Id uniqueidentifier - new order id (sequential, generated by the API)
--              @ClientOrderId uniqueidentifier - id generated by the customer's device
--              @CustomerId uniqueidentifier - id for the customer, used only when the phone is new
--              @Name nvarchar(120), @Phone nvarchar(10) - what the customer typed (trimmed, 10 digits)
--              @Total decimal(10,2) - sum of the item subtotals, computed by the API
--              @Now datetime2 - current time (UTC)
--              @MaxActiveOrders int - active orders (New, InPreparation, Ready) a phone may have
--              @ItemsJson nvarchar(max) - [{ Id, ProductId, Quantity, UnitPrice, Subtotal }]
--              @HistoryJson nvarchar(max) - [{ Id, FromStatus, ToStatus, ChangedById, CreatedAt }]
-- Returns:     Outcome nvarchar(20): Created, AlreadyExists (the ClientOrderId was already saved), or LimitReached;
--              OrderNumber int (null unless Created)
-- Author:      GuillermoRH19
-- Jira:        ITACR-12
-- =============================================================================
CREATE OR ALTER PROCEDURE dbo.usp_Order_CreatePickup
    @Id uniqueidentifier,
    @ClientOrderId uniqueidentifier,
    @CustomerId uniqueidentifier,
    @Name nvarchar(120),
    @Phone nvarchar(10),
    @Total decimal(10, 2),
    @Now datetime2,
    @MaxActiveOrders int,
    @ItemsJson nvarchar(max),
    @HistoryJson nvarchar(max)
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    DECLARE @Inserted TABLE (OrderNumber int NOT NULL);
    DECLARE @ExistingCustomerId uniqueidentifier;

    BEGIN TRY
        BEGIN TRANSACTION;

        IF EXISTS (SELECT 1 FROM dbo.Orders WITH (UPDLOCK, HOLDLOCK) WHERE ClientOrderId = @ClientOrderId)
        BEGIN
            ROLLBACK TRANSACTION;
            SELECT N'AlreadyExists' AS Outcome, CAST(NULL AS int) AS OrderNumber;
            RETURN;
        END;

        -- The lock on the phone serializes the orders of one phone, so the count below cannot be passed by a race.
        SELECT @ExistingCustomerId = Id FROM dbo.Customers WITH (UPDLOCK, HOLDLOCK) WHERE Phone = @Phone;

        IF @ExistingCustomerId IS NULL
        BEGIN
            SET @ExistingCustomerId = @CustomerId;
            INSERT INTO dbo.Customers (Id, Name, Phone, CreatedAt, UpdatedAt)
            VALUES (@ExistingCustomerId, @Name, @Phone, @Now, @Now);
        END
        ELSE
        BEGIN
            UPDATE dbo.Customers SET Name = @Name, UpdatedAt = @Now WHERE Id = @ExistingCustomerId;
        END;

        IF (SELECT COUNT(*) FROM dbo.Orders WHERE CustomerId = @ExistingCustomerId AND Status IN (N'New', N'InPreparation', N'Ready')) >= @MaxActiveOrders
        BEGIN
            -- The rollback also undoes the new customer or the new name: a refused order changes nothing.
            ROLLBACK TRANSACTION;
            SELECT N'LimitReached' AS Outcome, CAST(NULL AS int) AS OrderNumber;
            RETURN;
        END;

        INSERT INTO dbo.Orders (Id, ClientOrderId, Channel, Status, TableId, WaiterId, CustomerId, Total, LastStatusChangeAt, CreatedAt, UpdatedAt)
        OUTPUT inserted.OrderNumber INTO @Inserted (OrderNumber)
        VALUES (@Id, @ClientOrderId, N'MobileApp', N'New', NULL, NULL, @ExistingCustomerId, @Total, @Now, @Now, @Now);

        INSERT INTO dbo.OrderItems (Id, OrderId, ProductId, Quantity, UnitPrice, Subtotal, Size, Drink, Extras, Exclusions, CreatedAt, UpdatedAt)
        SELECT item.Id, @Id, item.ProductId, item.Quantity, item.UnitPrice, item.Subtotal, NULL, NULL, N'[]', N'[]', @Now, @Now
        FROM OPENJSON(@ItemsJson) WITH (
            Id uniqueidentifier,
            ProductId uniqueidentifier,
            Quantity int,
            UnitPrice decimal(10, 2),
            Subtotal decimal(10, 2)
        ) AS item;

        INSERT INTO dbo.OrderStatusHistory (Id, OrderId, FromStatus, ToStatus, ChangedById, CreatedAt, UpdatedAt)
        SELECT history.Id, @Id, history.FromStatus, history.ToStatus, history.ChangedById, history.CreatedAt, history.CreatedAt
        FROM OPENJSON(@HistoryJson) WITH (
            Id uniqueidentifier,
            FromStatus nvarchar(20),
            ToStatus nvarchar(20),
            ChangedById uniqueidentifier,
            CreatedAt datetime2
        ) AS history;

        COMMIT TRANSACTION;
        SELECT N'Created' AS Outcome, inserted.OrderNumber FROM @Inserted AS inserted;
    END TRY
    BEGIN CATCH
        IF @@TRANCOUNT > 0
        BEGIN
            ROLLBACK TRANSACTION;
        END;

        -- 2601/2627: a unique index rejected a concurrent duplicate that got past the locks. If the ClientOrderId was
        -- the one saved first, it is not an error; anything else is.
        IF ERROR_NUMBER() IN (2601, 2627) AND EXISTS (SELECT 1 FROM dbo.Orders WHERE ClientOrderId = @ClientOrderId)
        BEGIN
            SELECT N'AlreadyExists' AS Outcome, CAST(NULL AS int) AS OrderNumber;
            RETURN;
        END;

        THROW;
    END CATCH;
END;
