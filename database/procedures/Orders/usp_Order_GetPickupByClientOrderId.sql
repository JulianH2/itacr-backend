-- =============================================================================
-- Object:      dbo.usp_Order_GetPickupByClientOrderId
-- Type:        stored procedure
-- Purpose:     Returns a pickup order by the id its device generated, for the public status screen and for a repeated
--              request. It only answers orders of the MobileApp channel: a waiter order has a ClientOrderId too, but a
--              public endpoint has no reason to read it. It never returns the customer, the table, or the waiter.
--              The items come as JSON in the same row (one result set).
-- Parameters:  @ClientOrderId uniqueidentifier - id generated by the customer's device
-- Returns:     0 or 1 row: ClientOrderId, OrderNumber, Status, Total, CreatedAt,
--              ItemsJson (array of Name, Quantity, UnitPrice, Subtotal, in the order they were added)
-- Author:      GuillermoRH19
-- Jira:        ITACR-12
-- =============================================================================
CREATE OR ALTER PROCEDURE dbo.usp_Order_GetPickupByClientOrderId
    @ClientOrderId uniqueidentifier
AS
BEGIN
    SET NOCOUNT ON;

    SELECT o.ClientOrderId, o.OrderNumber, o.Status, o.Total, o.CreatedAt,
        (
            SELECT p.Name, i.Quantity, i.UnitPrice, i.Subtotal
            FROM dbo.OrderItems AS i
            JOIN dbo.Products AS p ON p.Id = i.ProductId
            WHERE i.OrderId = o.Id
            ORDER BY i.Id
            FOR JSON PATH
        ) AS ItemsJson
    FROM dbo.Orders AS o
    WHERE o.ClientOrderId = @ClientOrderId AND o.Channel = N'MobileApp';
END;
