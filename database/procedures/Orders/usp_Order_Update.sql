-- =============================================================================
-- Object:      dbo.usp_Order_Update
-- Type:        stored procedure
-- Purpose:     Modifies an order that the kitchen has not finished (HU_13): replaces its items, sets the table and the
--              total, marks it as modified, and adds a note when there is one, in one transaction. The order is only
--              changed while it belongs to @WaiterId and is still New or InPreparation; the status can change between the
--              read of the API and this write, so the guard is in the UPDATE and nothing else is touched when it fails.
--              The channel and the status never change here, and the history of statuses is not written.
-- Parameters:  @Id uniqueidentifier - order id
--              @WaiterId uniqueidentifier - waiter who is modifying it; it must be the one who took the order
--              @TableId uniqueidentifier - table of a dine-in order, null for a take-away order
--              @Total decimal(10,2) - sum of the item subtotals, computed by the API from menu prices
--              @Now datetime2 - current time (UTC): ModifiedAt and UpdatedAt
--              @NoteId uniqueidentifier - id of the new note (sequential, generated by the API); ignored without a note
--              @Note nvarchar(500) - note to add, or null
--              @ItemsJson nvarchar(max) - [{ Id, ProductId, Quantity, UnitPrice, Subtotal, Size, Drink, Extras, Exclusions }]
-- Returns:     Updated bit (0 when the order is not of @WaiterId or is no longer New or InPreparation; nothing changed)
-- Author:      JulianH2
-- Jira:        ITACR-19
-- =============================================================================
CREATE OR ALTER PROCEDURE dbo.usp_Order_Update
    @Id uniqueidentifier,
    @WaiterId uniqueidentifier,
    @TableId uniqueidentifier,
    @Total decimal(10, 2),
    @Now datetime2,
    @NoteId uniqueidentifier,
    @Note nvarchar(500),
    @ItemsJson nvarchar(max)
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    BEGIN TRY
        BEGIN TRANSACTION;

        UPDATE dbo.Orders
        SET TableId = @TableId,
            Total = @Total,
            ModifiedAt = @Now,
            UpdatedAt = @Now
        WHERE Id = @Id AND WaiterId = @WaiterId AND Status IN (N'New', N'InPreparation');

        IF @@ROWCOUNT = 0
        BEGIN
            ROLLBACK TRANSACTION;
            SELECT CAST(0 AS bit) AS Updated;
            RETURN;
        END;

        DELETE FROM dbo.OrderItems WHERE OrderId = @Id;

        INSERT INTO dbo.OrderItems (Id, OrderId, ProductId, Quantity, UnitPrice, Subtotal, Size, Drink, Extras, Exclusions, CreatedAt, UpdatedAt)
        SELECT item.Id, @Id, item.ProductId, item.Quantity, item.UnitPrice, item.Subtotal, item.Size, item.Drink,
            COALESCE(item.Extras, N'[]'), COALESCE(item.Exclusions, N'[]'), @Now, @Now
        FROM OPENJSON(@ItemsJson) WITH (
            Id uniqueidentifier,
            ProductId uniqueidentifier,
            Quantity int,
            UnitPrice decimal(10, 2),
            Subtotal decimal(10, 2),
            Size nvarchar(60),
            Drink nvarchar(60),
            Extras nvarchar(max) AS JSON,
            Exclusions nvarchar(max) AS JSON
        ) AS item;

        IF @Note IS NOT NULL
        BEGIN
            INSERT INTO dbo.OrderNotes (Id, OrderId, [Text], CreatedAt, UpdatedAt)
            VALUES (@NoteId, @Id, @Note, @Now, @Now);
        END;

        COMMIT TRANSACTION;
        SELECT CAST(1 AS bit) AS Updated;
    END TRY
    BEGIN CATCH
        IF @@TRANCOUNT > 0
        BEGIN
            ROLLBACK TRANSACTION;
        END;

        THROW;
    END CATCH;
END;
