-- =============================================================================
-- Object:      dbo.usp_Notification_CreateOrderReady
-- Type:        stored procedure
-- Purpose:     Records the "order ready" notice of an order and returns who receives it (HU_09): the waiter who took it,
--              or the customer of a pickup order. Only one notice per order: if the kitchen undoes Ready and marks it
--              again, nothing new is recorded. Nothing is recorded either when the order is no longer Ready.
-- Parameters:  @Id uniqueidentifier - new notification id (sequential, generated by the API)
--              @OrderId uniqueidentifier - the order that became Ready
--              @Now datetime2 - current time (UTC), stored as SentAt, CreatedAt and UpdatedAt
-- Returns:     0 or 1 row: OrderNumber, Channel, TableNumber, WaiterId, CustomerId - no row when nothing was recorded
-- Author:      JulianH2
-- Jira:        ITACR-15
-- =============================================================================
CREATE OR ALTER PROCEDURE dbo.usp_Notification_CreateOrderReady
    @Id uniqueidentifier,
    @OrderId uniqueidentifier,
    @Now datetime2
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    BEGIN TRANSACTION;

    IF NOT EXISTS (SELECT 1 FROM dbo.Orders WHERE Id = @OrderId AND Status = N'Ready')
       OR EXISTS (SELECT 1 FROM dbo.Notifications WITH (UPDLOCK, HOLDLOCK) WHERE OrderId = @OrderId AND Type = N'OrderReady')
    BEGIN
        COMMIT TRANSACTION;
        RETURN;
    END;

    INSERT INTO dbo.Notifications (Id, Type, RecipientEmployeeId, RecipientCustomerId, OrderId, SentAt, CreatedAt, UpdatedAt)
    SELECT @Id, N'OrderReady', o.WaiterId, o.CustomerId, o.Id, @Now, @Now, @Now
    FROM dbo.Orders AS o
    WHERE o.Id = @OrderId;

    COMMIT TRANSACTION;

    SELECT o.OrderNumber, o.Channel, t.Number AS TableNumber, o.WaiterId, o.CustomerId
    FROM dbo.Orders AS o
    LEFT JOIN dbo.DiningTables AS t ON t.Id = o.TableId
    WHERE o.Id = @OrderId;
END;
