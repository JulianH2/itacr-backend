-- =============================================================================
-- Object:      dbo.usp_Employee_Register
-- Type:        stored procedure
-- Purpose:     Saves the account a new employee asked for from the login screen (HU_14): status PendingApproval, no password,
--              and the time they accepted the privacy notice. A manager approves it later. The email or user is unique
--              (the index IX_Employees_Email), so when it is already taken nothing is saved and Created is 0. The check
--              runs under a range lock and the unique index is the last guard, so two requests for the same email at the
--              same moment cannot both succeed.
-- Parameters:  @Id uniqueidentifier - new employee id (sequential, generated by the API)
--              @FullName nvarchar(120), @Email nvarchar(254), @Phone nvarchar(20) - as typed, trimmed
--              @Role nvarchar(20) - Waiter or Kitchen; the API never sends Manager
--              @PinHash nvarchar(255) - hash of the PIN; the PIN itself is never stored
--              @PrivacyNoticeAcceptedAt datetime2 - when the privacy notice was accepted (UTC)
--              @Now datetime2 - current time (UTC): CreatedAt and UpdatedAt
-- Returns:     Created bit (0 when the email or user already exists)
-- Author:      GuillermoRH19
-- Jira:        ITACR-20
-- =============================================================================
CREATE OR ALTER PROCEDURE dbo.usp_Employee_Register
    @Id uniqueidentifier,
    @FullName nvarchar(120),
    @Email nvarchar(254),
    @Phone nvarchar(20),
    @Role nvarchar(20),
    @PinHash nvarchar(255),
    @PrivacyNoticeAcceptedAt datetime2,
    @Now datetime2
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    BEGIN TRY
        BEGIN TRANSACTION;

        IF EXISTS (SELECT 1 FROM dbo.Employees WITH (UPDLOCK, HOLDLOCK) WHERE Email = @Email)
        BEGIN
            ROLLBACK TRANSACTION;
            SELECT CAST(0 AS bit) AS Created;
            RETURN;
        END;

        INSERT INTO dbo.Employees (Id, FullName, Email, Phone, Role, PinHash, PasswordHash, Status, ApprovedById, PrivacyNoticeAcceptedAt, CreatedAt, UpdatedAt)
        VALUES (@Id, @FullName, @Email, @Phone, @Role, @PinHash, NULL, N'PendingApproval', NULL, @PrivacyNoticeAcceptedAt, @Now, @Now);

        COMMIT TRANSACTION;
        SELECT CAST(1 AS bit) AS Created;
    END TRY
    BEGIN CATCH
        IF @@TRANCOUNT > 0
        BEGIN
            ROLLBACK TRANSACTION;
        END;

        -- 2601/2627: the unique index on Email rejected a concurrent duplicate that got past the lock.
        IF ERROR_NUMBER() IN (2601, 2627)
        BEGIN
            SELECT CAST(0 AS bit) AS Created;
            RETURN;
        END;

        THROW;
    END CATCH;
END;
